package com.example.springexample.Services;

/**
 * Исход проверки членства в чате (beads 8wh).
 *
 * До этого тикета исходов было два: булев {@code false} означал одновременно
 * «пользователя нет в списке» и «список получить не удалось». Разница существенная:
 * первое — ответ, второе — его отсутствие. На SUBSCRIBE это стоило пользователю всей
 * WebSocket-сессии при любой транзиентной заминке MessegerParody.
 */
public enum MembershipDecision {
    /** Список участников получен, пользователь в нём есть. */
    MEMBER,
    /**
     * Список участников получен, пользователя в нём нет. Сюда же — пустой список:
     * существующий чат всегда имеет хотя бы одного участника, поэтому пустота вероятнее
     * означает удалённый чат, чем сбой. Трактовать её как {@link #UNKNOWN} нельзя —
     * клиент ушёл бы в бесконечный цикл переподписок на несуществующий чат.
     */
    NOT_MEMBER,
    /** Таймаут или ошибка вызова: выяснить не удалось. Это НЕ отказ по членству. */
    UNKNOWN
}
